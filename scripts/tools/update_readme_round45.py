"""README 缺口段随第四、五轮补采更新。

变化：捷克 4 本、比利时 2 本、日本 1 本小册子入目录，此前均无。
仅剩葡萄牙、瑞典仍无小册子。
"""

import io
import os
import re
import sys

BASE = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
README = os.path.join(BASE, "README.md")


def main():
    s = io.open(README, encoding="utf-8").read()
    orig = s

    # 「日本、捷克、葡萄牙至今没有一本小册子」→ 只剩葡萄牙、瑞典
    s = re.sub(
        r"- \*\*日本、捷克、葡萄牙至今没有一本小册子\*\*。按母语种检索 Internet Archive，"
        r"这三国的命中主要是期刊、法令汇编与学术论文：捷克语政治类命中为 0，日语政治类命中为 0，"
        r"葡萄牙语命中的多是咖啡与关税经济文书、协会章程。这三地目前只有单页海报／传单"
        r"（日本 \d+、葡萄牙 \d+、捷克 \d+）。",
        "- **葡萄牙、瑞典至今没有一本小册子**。葡萄牙语检索命中的多是咖啡与关税经济文书、"
        "协会章程（如里斯本犹太会堂章程），瑞典语命中的多为仲夏节活动手册与农业合作社年报；"
        "改用英/法/德文编目检索后仍未见合格的政党纲领或宣传册。这两地目前只有单页"
        "（葡萄牙 9 件、瑞典 1 件）。\n"
        "- 捷克、比利时、日本已从 IA 补到小册子（2026-10-28）。关键在**编目语种**："
        "这些国别的材料在 IA 上多以英/法/德文编目，用母语种检索几乎全漏。改用西文编目后得到"
        "捷共 1968 年行动纲领、马萨里克三种民族宣传册、比利时工人党第三十二次年会记录、"
        "内珀《日本共产党概观》（1913）等。",
        s)

    # 波兰那段后面补上第四五轮的说明
    s = re.sub(
        r"(同批检索到的捷克语材料只有芝加哥铁匠工会章程，非政党文献，未收。)",
        r"\1\n"
        "- 第四、五轮补采（2026-10-28）另得 11 本：捷克 4、比利时 2、日本 1、"
        "奥地利 1（贝拉·库恩《革命文集》，英国社会党出版）、意大利 1（墨索里尼"
        "《法西斯主义的政治与社会学说》1932）、西班牙 1（《费雷尔的「审判」》1911，"
        "纽约劳工新闻社）、匈牙利 1（第一个五年计划法，1950）。",
        s)

    if s != orig:
        io.open(README, "w", encoding="utf-8", newline="\n").write(s)
        print("README 缺口段已更新")
    else:
        print("未匹配，未改动")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main() or 0)
