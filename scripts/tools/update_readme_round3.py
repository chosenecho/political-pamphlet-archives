"""README 缺口段随本轮补采更新。

本轮变化：
  · 波兰 3 本、拉美 3 本、苏联 2 本小册子入目录（此前这三地均无小册子）
  · 2026-10 因 IA 不可达而未下完的两本，现已续传补齐并入目录
  · 印度补 1 本（《素食的道德基础》）、英国补 1 本（I.L.P. 纲领）
"""

import io
import os
import re
import sys

BASE = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
README = os.path.join(BASE, "README.md")


def main():
    s = io.open(README, encoding="utf-8").read()
    orig = s

    # 1) 「日本、捷克、波兰、葡萄牙至今没有一本小册子」→ 波兰已有
    s = re.sub(
        r"- \*\*日本、捷克、波兰、葡萄牙至今没有一本小册子\*\*。按母语种检索 Internet Archive，"
        r"这四国的命中主要是期刊、法令汇编与学术论文：波兰语 `program` 命中的是战后党史教材，"
        r"捷克语政治类命中为 0，日语政治类命中为 0，葡萄牙语命中的多是咖啡与关税经济文书。"
        r"这四个国别目前只有单页海报／传单（波兰 \d+、日本 \d+、葡萄牙 \d+、捷克 \d+）。",
        "- **日本、捷克、葡萄牙至今没有一本小册子**。按母语种检索 Internet Archive，"
        "这三国的命中主要是期刊、法令汇编与学术论文：捷克语政治类命中为 0，日语政治类命中为 0，"
        "葡萄牙语命中的多是咖啡与关税经济文书、协会章程。这三地目前只有单页海报／传单"
        "（日本 10、葡萄牙 9、捷克 4）。\n"
        "- 波兰已从 IA 补到 3 本（2026-10-28）：民族民主党 1905 年利沃夫纲领、"
        "社会党第十次代表大会《纲领·策略·组织》（1908）、霍恩-弗龙斯基《告斯拉夫各民族书》"
        "（1848，弥赛亚主义政治檄文）。同批检索到的捷克语材料只有芝加哥铁匠工会章程，"
        "非政党文献，未收。",
        s)

    # 2) 苏联/比利时/瑞典：苏联已有 2 本
    s = re.sub(
        r"- 苏联、比利时、瑞典同样只有单页而没有小册子：苏联 \d+ 件（[^）]*）、"
        r"比利时 \d+ 件（[^）]*）、瑞典 \d+ 件（[^）]*）。这三国的政党小册子在 Commons 上未数字化，"
        r"IA 侧又被前述限流与不可达挡住。",
        "- 比利时、瑞典仍只有单页而没有小册子：比利时 1 件（1942 年《与工人士兵一起为社会主义》）、"
        "瑞典 1 件（1930 年社民党《我们在建设国家》）。这两国的政党小册子在 Commons 上未数字化。\n"
        "- 苏联已从 IA 补到 2 本（2026-10-28）：《狡猾的机械》（1919 年苏俄内战政治宣传读物）、"
        "《白芬兰野兽》（1943 年战时宣传册）。",
        s)

    # 3) 待续传那段：已补齐
    s = re.sub(
        r"- \*\*2026-10 补采时 Internet Archive 中途不可达\*\*（`archive\.org` 全部端点超时，"
        r"同期 Commons 与抗战平台正常，属单点故障而非本地网络问题）。已有两本只下到部分页图，"
        r"未入目录，保留在 `images/` 下待续传：《素食的道德基础》（14/40 页）、"
        r"《I\.L\.P\. 纲领与失业》（3/24 页）。续传脚本 `scripts/harvest_resume\.py` 支持断点续抓，"
        r"IA 恢复后重跑即可补齐。",
        "- **2026-10 那次 Internet Archive 中途不可达**（`archive.org` 全部端点超时，"
        "同期 Commons 与抗战平台正常，属单点故障而非本地网络问题）导致两本只下到部分页图："
        "《素食的道德基础》（14/40 页）、《I.L.P. 纲领与失业》（3/24 页）。"
        "IA 恢复后已用 `scripts/tools/resume_pending.py` 续传补齐（40/40、24/24），"
        "两本均已入目录。断点续传与熔断逻辑见 `scripts/harvest_resume.py`。",
        s)

    if s != orig:
        io.open(README, "w", encoding="utf-8", newline="\n").write(s)
        print("README 缺口段已更新")
    else:
        print("未匹配到目标段落，未改动")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main() or 0)
