"""`data/sources.json` 的 `region` 字段词表：代码 → 统一中文名。

为什么要有这个模块
    这个字段原本是混用的：`UK`/`US`/`DE`/`FR`/`NL`/`CH`/`ES`/`CN`/`JP`/`BE`
    是 ISO 代码，`智利`/`奥地利`/`跨国`/`欧洲`/`波兰`…是中文名，另有
    `US/UK`、`俄/美`、`印度/美` 三个复合值。24 种取值描述 40 条记录，
    同一件事两种写法。

    后果不是「不好看」，是**下游各写各的映射**：
      - `add_terms.py` 的 REGION_LANG 把 `UK` 和「英国」都列进去，
        才勉强能覆盖——新增一个国家而漏改这里，语言的检索词就会静默退回英文
      - `build_index.py` 把 region 原样写进 csv 与 COLLECTIONS.md，
        于是文档里一半中文一半代码
      - README 的节选表又是第三种写法

    所以词表收进这里一处，数据改成统一中文名，所有消费方都从本模块取中文。

改法
    数据侧：`sources.json` 的 region 一律写成中文名（见 CANONICAL）。
    读取侧：一律经 `to_zh()` 转换，兼容旧数据里残留的代码写法。
"""

#: 代码 / 旧写法 → 统一中文名。
#: 复合值保留「甲/乙」的形状，因为它表达的是「两地合藏」或「跨国机构」，
#: 压成单一国家会失真。
