def language_of(region):
    """region 对应语言代码。查不到返回 None，由调用方决定怎么办。

    刻意不兜底成 `en`：兜底会让新增国别「看起来正常」却拿到错误的检索词，
    这正是这份表以前的问题。宁可在审核里报出来。
    """
    return LANGUAGE.get(to_zh(region))
